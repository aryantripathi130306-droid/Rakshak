// ─────────────────────────────────────────────────────────────────────────────
// app/api/reports/[id]/download/route.ts
// GET /api/reports/:id/download — Download generated report payload
// ─────────────────────────────────────────────────────────────────────────────
import { type NextRequest } from "next/server";
import prisma from "@/lib/prisma";
import { authenticateOfficer, hasPermission, logAuditEvent } from "@/services/authService";

export const runtime = "nodejs";

export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const auth = await authenticateOfficer(request);
    if (!auth || !hasPermission(auth.officer.role, "reports:download")) {
      return Response.json(
        { error: "Access denied: requires reports:download permission" },
        { status: 403 }
      );
    }

    const p = prisma as any;
    const report = await p.generatedReport.findFirst({
      where: {
        OR: [{ id }, { reportNumber: id }],
      },
    });

    if (!report) {
      return Response.json({ error: "Report not found" }, { status: 404 });
    }

    const ipAddress = request.headers.get("x-forwarded-for")?.split(",")[0].trim() || "103.45.67.89";
    await logAuditEvent({
      officerId: auth.officer.id,
      officerName: auth.officer.name,
      officerBadge: auth.officer.badgeNumber,
      action: "DOWNLOAD_REPORT",
      module: "Reports",
      targetType: "Report",
      targetId: report.id,
      details: `Downloaded report ${report.reportNumber} (${report.outputFormat})`,
      result: "SUCCESS",
      ipAddress,
    });

    const parsedMetadata = report.metadata ? JSON.parse(report.metadata) : { reportNumber: report.reportNumber };

    if (report.outputFormat === "JSON") {
      return new Response(JSON.stringify(parsedMetadata, null, 2), {
        status: 200,
        headers: {
          "Content-Type": "application/json",
          "Content-Disposition": `attachment; filename="Rakshak_${report.reportNumber}.json"`,
        },
      });
    }

    // Return text representation for PDF/Doc download
    const reportText = `================================================================================
RAKSHAK FORENSIC DIGITAL EVIDENCE INTELLIGENCE PLATFORM
CONFIDENTIAL // LAW ENFORCEMENT INVESTIGATION REPORT
================================================================================
Report Reference : ${report.reportNumber}
Report Title     : ${report.title}
Report Type      : ${report.reportType}
Generated By     : ${report.generatedBy}
Generated Date   : ${report.createdAt}
Format           : ${report.outputFormat}
Status           : ${report.status}
Sections         : ${report.sectionsIncluded}

METADATA SUMMARY:
${JSON.stringify(parsedMetadata, null, 2)}
================================================================================
`;

    return new Response(reportText, {
      status: 200,
      headers: {
        "Content-Type": "text/plain; charset=utf-8",
        "Content-Disposition": `attachment; filename="Rakshak_${report.reportNumber}.txt"`,
      },
    });
  } catch (err) {
    console.error("[GET /api/reports/[id]/download] Error:", err);
    return Response.json({ error: "Download failed" }, { status: 500 });
  }
}
