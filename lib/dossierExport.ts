import crypto from "node:crypto";
import path from "node:path";
import prisma from "./prisma.ts";
import { canAccessDepartmentAsync, hasPermission, type OfficerProfile } from "./accessControl.ts";

export type ExportFormat = "JSON" | "TXT" | "ZIP" | "PDF";

export interface ExportResult {
  success: boolean;
  statusCode: number;
  buffer?: Buffer;
  mimeType?: string;
  filename?: string;
  artifactHash?: string;
  auditId?: string;
  error?: string;
}

/**
 * Sanitizes user-supplied filenames to prevent path traversal or unsafe characters.
 */
export function sanitizeExportFilename(name: string, fallback: string = "dossier_export"): string {
  if (!name) return fallback;
  // Extract basename to block ../ or path traversal
  const base = path.basename(name);
  // Allow alphanumeric, underscores, hyphens, dots
  const sanitized = base.replace(/[^a-zA-Z0-9_\-\.]/g, "_").trim();
  return sanitized.length > 0 ? sanitized : fallback;
}

/**
 * Formats a clean, watermarked text report for display or PDF export.
 */
export function formatDossierTextDocument(dossier: any, content: any): string {
  const isFinalized = dossier.status === "FINALIZED";
  const isApproved = dossier.status === "APPROVED";
  const watermark = isFinalized
    ? "FINALIZED // OFFICIALLY APPROVED FOR JUDICIAL PROCEEDING"
    : isApproved
    ? "APPROVED // PENDING FINAL ISSUANCE"
    : `DRAFT (${dossier.status}) // STRICTLY NOT FOR JUDICIAL SUBMISSION`;

  const certSection = isFinalized || isApproved
    ? `
================================================================================
STATUTORY CERTIFICATION UNDER SECTION 63 OF BHARATIYA SAKSHYA ADHINIYAM, 2023
================================================================================
Certifying Supervisor : ${dossier.approvedByName || "Authorised Officer"} [${dossier.approvedByBadge || "N/A"}]
Approval Timestamp    : ${dossier.approvedAt ? new Date(dossier.approvedAt).toISOString() : "N/A"}
Bound Content SHA-256 : ${dossier.approvalBoundHash || "N/A"}

Declaration:
I hereby certify that the electronic evidence items referenced herein were collected,
preserved, and cryptographically verified under established standard operating procedures.
Hash values correspond to original intake manifests without alteration.
`
    : `
================================================================================
STATUTORY CERTIFICATION STATUS: PENDING SUPERVISOR REVIEW & APPROVAL
================================================================================
This draft report has NOT been certified under Section 63 of Bharatiya Sakshya Adhiniyam, 2023.
No statutory authority may be inferred from this document until formal supervisor approval.
`;

  return `================================================================================
RAKSHAK FORENSIC DIGITAL EVIDENCE INTELLIGENCE PLATFORM
CONFIDENTIAL // LAW ENFORCEMENT PROCEEDING EXHIBIT
================================================================================
[WATERMARK] ${watermark}
================================================================================
Dossier Reference : ${dossier.dossierNumber}
Case Reference    : ${content.caseInformation?.caseNumber || "N/A"}
Incident Type     : ${content.caseInformation?.incidentType || "N/A"}
Complainant       : ${content.caseInformation?.complainantName || "N/A"}
Version Number    : v${dossier.version} (${dossier.status})
Template Version  : ${dossier.templateVersion}
Generated By      : ${dossier.generatedByName} [${dossier.generatedByBadge || "N/A"}]
Generated Date    : ${dossier.generatedAt ? new Date(dossier.generatedAt).toISOString() : "N/A"}
Content SHA-256   : ${dossier.contentHash}
${certSection}
================================================================================
1. CASE SUMMARY & SCOPE
================================================================================
${content.caseSummary || "No summary provided."}

Primary Jurisdiction : ${content.investigationScope?.primaryJurisdiction || "N/A"}
Reporting Period     : ${content.investigationScope?.reportingPeriodStart} to ${content.investigationScope?.reportingPeriodEnd}

================================================================================
2. EVIDENCE EXHIBITS INVENTORY
================================================================================
${(content.evidenceInventory || [])
  .map(
    (ev: any, idx: number) =>
      `[${idx + 1}] Exhibit: ${ev.fileName} (${ev.fileType}, ${ev.fileSizeBytes} bytes)
    SHA-256: ${ev.sha256Hash}
    Integrity: ${ev.integrityVerified ? "VERIFIED MATCH" : "DISCREPANCY DETECTED"}
    Cold Vault: ${ev.storageState}`
  )
  .join("\n\n")}

================================================================================
3. CHAIN OF CUSTODY SUMMARY
================================================================================
${(content.custodySummary || [])
  .map(
    (ce: any) =>
      `Seq #${ce.sequenceNumber} [${ce.eventType}] at ${ce.timestampUTC}
    Custodian: ${ce.custodianName} [${ce.custodianBadge || "N/A"}]
    Integrity Hash: ${ce.integrityHash}`
  )
  .join("\n\n")}

================================================================================
4. ANALYST-CONFIRMED INTELLIGENCE LINKS
================================================================================
${(content.reviewedIntelligenceLinks || []).length > 0
  ? (content.reviewedIntelligenceLinks || [])
      .map(
        (l: any) =>
          `- ${l.entityType} (${l.maskedValue}) linked to ${l.targetCaseNumber}
    Rule: ${l.matchRule} | Status: ${l.status}
    Explanation: ${l.explanation}
    Reviewed By: ${l.reviewedBy || "Analyst"}`
      )
      .join("\n")
  : "No confirmed cross-case relationships recorded."}

================================================================================
5. OUTSTANDING INVESTIGATIVE LEADS (CANDIDATES ONLY)
================================================================================
${(content.outstandingInvestigativeLeads || []).length > 0
  ? (content.outstandingInvestigativeLeads || [])
      .map(
        (cand: any) =>
          `[LEAD ONLY] ${cand.entityType} (${cand.maskedValue})
    Rule: ${cand.matchRule}
    Limitations: ${cand.limitations}
    Disclaimer: ${cand.disclaimer}`
      )
      .join("\n")
  : "No outstanding candidate leads."}

================================================================================
6. CONTRADICTORY & UNRESOLVED DISCREPANCIES
================================================================================
${(content.contradictoryAndUnresolved || []).length > 0
  ? (content.contradictoryAndUnresolved || [])
      .map((c: any) => `- [${c.nature}] ${c.topic}: ${c.details}`)
      .join("\n")
  : "None recorded."}

================================================================================
END OF DOSSIER EXHIBIT // RAKSHAK v3.0
================================================================================
`;
}

/**
 * Executes a controlled, audited export of an investigative dossier.
 */
export async function exportInvestigativeDossier(
  dossierId: string,
  requester: OfficerProfile,
  format: ExportFormat = "JSON",
  prismaOverride?: any
): Promise<ExportResult> {
  const p = (prismaOverride ?? prisma) as any;

  // 1. Verify officer status
  const dbOfficer = await p.officer.findUnique({
    where: { id: requester.id },
    select: { id: true, name: true, badgeNumber: true, role: true, status: true, departmentId: true, jurisdiction: true },
  });

  if (!dbOfficer || dbOfficer.status !== "ACTIVE") {
    return {
      success: false,
      statusCode: 403,
      error: `Export denied: Officer account is ${dbOfficer ? dbOfficer.status : "NON_EXISTENT"}. Active account required.`,
    };
  }

  // 2. Permission check: reports:download
  if (!hasPermission(dbOfficer.role, "reports:download") && !hasPermission(dbOfficer.role, "case:read")) {
    return {
      success: false,
      statusCode: 403,
      error: `Export denied: Role ${dbOfficer.role} lacks reports:download permission.`,
    };
  }

  // 3. Fetch Dossier and Case
  const dossier = await p.investigativeDossier.findUnique({
    where: { id: dossierId },
    include: {
      case: { select: { id: true, caseNumber: true, departmentId: true, jurisdiction: true } },
    },
  });

  if (!dossier) {
    return {
      success: false,
      statusCode: 404,
      error: `Dossier not found: ${dossierId}`,
    };
  }

  // 4. Case-Level Authorization & Department Isolation Check
  const canAccess = await canAccessDepartmentAsync(
    dbOfficer,
    dossier.case.jurisdiction,
    dossier.case.departmentId,
    p
  );

  if (!canAccess) {
    return {
      success: false,
      statusCode: 403,
      error: "Export denied: Target dossier belongs to another departmental jurisdiction without an active access grant.",
    };
  }

  let content: any = {};
  try {
    content = JSON.parse(dossier.contentJson);
  } catch (_) {
    return {
      success: false,
      statusCode: 500,
      error: "Dossier content corrupted or unparseable.",
    };
  }

  // 5. Build Format-Specific Buffer
  let buffer: Buffer;
  let mimeType: string;
  let extension: string;

  if (format === "JSON") {
    const jsonStr = JSON.stringify(
      {
        dossierNumber: dossier.dossierNumber,
        version: dossier.version,
        status: dossier.status,
        contentHash: dossier.contentHash,
        approvalBoundHash: dossier.approvalBoundHash,
        approvedByName: dossier.approvedByName,
        approvedAt: dossier.approvedAt,
        content,
      },
      null,
      2
    );
    buffer = Buffer.from(jsonStr, "utf-8");
    mimeType = "application/json";
    extension = "json";
  } else {
    // TXT or PDF text representation
    const textDoc = formatDossierTextDocument(dossier, content);
    buffer = Buffer.from(textDoc, "utf-8");
    mimeType = "text/plain; charset=utf-8";
    extension = "txt";
  }

  const filename = sanitizeExportFilename(
    `Rakshak_Dossier_${dossier.case.caseNumber}_v${dossier.version}.${extension}`
  );
  const artifactHash = crypto.createHash("sha256").update(buffer).digest("hex");

  // 6. Record Audit in DossierExportAudit if available
  let auditRecordId: string | undefined;
  try {
    if (p.dossierExportAudit) {
      const exportAuditNumber = `${dossier.dossierNumber}-EXP-${Date.now().toString(36).toUpperCase()}-${Math.floor(Math.random() * 1000)}`;
      const auditRec = await p.dossierExportAudit.create({
        data: {
          dossierNumber: exportAuditNumber,
          caseId: dossier.caseId,
          exportFormat: format,
          officerName: dbOfficer.name,
          officerBadge: dbOfficer.badgeNumber,
          templateVersion: dossier.templateVersion,
          validationStatus: "COMPLETE",
          evidenceCount: content.evidenceInventory?.length || 0,
          manifestHash: artifactHash,
        },
      });
      auditRecordId = auditRec.id;
    }
  } catch (auditErr) {
    console.warn("Could not record DossierExportAudit:", auditErr);
  }

  return {
    success: true,
    statusCode: 200,
    buffer,
    mimeType,
    filename,
    artifactHash,
    auditId: auditRecordId,
  };
}
