// ─────────────────────────────────────────────────────────────────────────────
// scripts/test_page05_verification.mjs
// Verification script testing Page 05: Reports & Dossiers backend routes & data
// ─────────────────────────────────────────────────────────────────────────────
import path from "node:path";
import { PrismaClient } from "@prisma/client";

const dbUrl = process.env.DATABASE_URL || `file:${path.resolve("prisma/dev.db")}`;
const prisma = new PrismaClient({
  datasources: { db: { url: dbUrl } },
});

async function main() {
  console.log("=== VERIFYING PAGE 05: REPORTS & FORENSIC DOSSIERS ===");

  // 1. Verify Reports Counts
  const total = await prisma.generatedReport.count();
  const completed = await prisma.generatedReport.count({ where: { status: "COMPLETED" } });
  const draft = await prisma.generatedReport.count({ where: { status: "IN_DRAFT" } });
  const review = await prisma.generatedReport.count({ where: { status: "UNDER_REVIEW" } });
  const templates = await prisma.scheduledReport.count();

  console.log(`[1] Database Counts:`);
  console.log(`    • Total Reports:   ${total} (Expected: 28)`);
  console.log(`    • Completed:       ${completed} (Expected: 18)`);
  console.log(`    • In Draft:        ${draft} (Expected: 6)`);
  console.log(`    • Under Review:    ${review} (Expected: 3)`);
  console.log(`    • Templates:       ${templates} (Expected: 5)`);

  if (total !== 28 || completed !== 18 || draft !== 6 || review !== 3) {
    throw new Error(`Counts mismatch: total=${total}, completed=${completed}, draft=${draft}, review=${review}`);
  }

  // 2. Verify Primary Report RPT-2025-0047
  const rpt47 = await prisma.generatedReport.findUnique({
    where: { reportNumber: "RPT-2025-0047" },
  });
  if (!rpt47) throw new Error("RPT-2025-0047 not found");

  const meta = JSON.parse(rpt47.metadata || "{}");
  console.log(`\n[2] Primary Report Dossier (RPT-2025-0047):`);
  console.log(`    • Title:           ${rpt47.title}`);
  console.log(`    • Category:        ${meta.category}`);
  console.log(`    • Case:            ${meta.caseNumber}`);
  console.log(`    • Generated By:    ${rpt47.generatedBy}`);
  console.log(`    • Evidence Files:  ${meta.metrics?.evidenceFiles}`);
  console.log(`    • Key Findings:    ${meta.metrics?.keyFindings}`);

  // 3. Verify Associated Case Evidence and Findings
  const linkedCase = await prisma.case.findFirst({
    where: { id: rpt47.caseId },
    include: {
      evidence: { include: { facts: true } },
      timeline: true,
      entities: true,
    },
  });

  if (!linkedCase) throw new Error("Linked case for RPT-2025-0047 not found");
  console.log(`\n[3] Linked Forensic Evidence & Findings:`);
  console.log(`    • Case Number:     ${linkedCase.caseNumber}`);
  console.log(`    • Evidence Items:  ${linkedCase.evidence.length}`);
  console.log(`    • Timeline Events: ${linkedCase.timeline.length}`);
  console.log(`    • Entities:        ${linkedCase.entities.length}`);

  const totalFacts = linkedCase.evidence.reduce((acc, ev) => acc + ev.facts.length, 0);
  console.log(`    • Extracted Facts: ${totalFacts}`);

  // 4. Verify Dual-Hash Verification on Evidence
  const unverified = linkedCase.evidence.filter((ev) => ev.sha256Hash !== ev.clientHash);
  console.log(`    • Hash Mismatches: ${unverified.length} (Expected: 0)`);
  if (unverified.length > 0) throw new Error("Evidence hash mismatch detected!");

  // 5. Verify Scheduled Templates
  const allTemplates = await prisma.scheduledReport.findMany();
  console.log(`\n[4] Standard Templates (${allTemplates.length}):`);
  allTemplates.forEach((t) => {
    console.log(`    • ${t.name} [${t.reportType}] (${t.frequency})`);
  });

  console.log("\n=== ALL PAGE 05 VERIFICATION CHECKS PASSED ===");
  await prisma.$disconnect();
}

main().catch((err) => {
  console.error("Verification failed:", err);
  process.exit(1);
});
